#!/usr/bin/env node
/**
 * Write `ios/.xcode.env.local` with an absolute path to node.
 *
 * Why this exists: `ios/.xcode.env` ships `export NODE_BINARY=$(command -v
 * node)`, and Xcode runs script phases under a restricted PATH that does not
 * include Homebrew. `command -v node` finds nothing, `NODE_BINARY` resolves
 * empty, and the Hermes phase fails with the uniquely unhelpful
 *
 *   Script-46EB2E00023A30.sh: line 9: : command not found
 *   Command PhaseScriptExecution failed with a nonzero exit code
 *
 * A command-line build works, because there the shell PATH is intact — so the
 * failure looks like broken source when it is only a broken environment.
 *
 * `.xcode.env.local` is the sanctioned override and is gitignored, which is
 * also why this has to be a script rather than a committed file: `ios/` is
 * generated, ignored wholesale, and `npm run prebuild` runs `expo prebuild
 * --clean`, which deletes the directory. Anything written there by hand
 * survives exactly until the next prebuild. Wiring this into `postprebuild`
 * and `postinstall` is what makes the fix outlive the regeneration.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IOS_DIR = join(PROJECT, 'ios');

// Nothing to configure before the native project is generated. Not an error:
// this runs from postinstall too, and a fresh clone has no ios/ yet.
if (!existsSync(IOS_DIR)) {
  console.log('write-xcode-env: no ios/ yet, skipping');
  process.exit(0);
}

/**
 * Prefer what PATH resolves over `process.execPath`.
 *
 * On Homebrew `process.execPath` is the versioned Cellar path
 * (`/opt/homebrew/Cellar/node/26.7.0/bin/node`), which stops existing at the
 * next `brew upgrade node` — trading a missing path for a stale one, and a
 * stale one fails later and more confusingly. `/opt/homebrew/bin/node` is a
 * symlink Homebrew maintains across upgrades. Same reasoning rejects an nvm
 * shim, which moves whenever the selected version changes; if that is all
 * there is, the version-pinned path is still better than nothing and the
 * comment in the generated file says so.
 */
function resolveNode() {
  try {
    const fromPath = execFileSync('/usr/bin/which', ['node'], { encoding: 'utf8' }).trim();
    // Only trust it if it is genuinely the same binary we are running under,
    // so a shadowed or half-installed node cannot be baked into the build.
    if (fromPath && realpathSync(fromPath) === realpathSync(process.execPath)) {
      return fromPath;
    }
  } catch {
    // Fall through — execPath is always available.
  }
  return process.execPath;
}

const nodeBinary = resolveNode();
const target = join(IOS_DIR, '.xcode.env.local');

writeFileSync(
  target,
  [
    '# Generated by scripts/write-xcode-env.mjs. Do not edit; rerun',
    '# `node scripts/write-xcode-env.mjs` instead.',
    '#',
    "# Xcode's script phases run under a restricted PATH, so the `command -v node`",
    '# in .xcode.env resolves to nothing and the Hermes phase dies with',
    '# "line 9: : command not found". An absolute path is the fix.',
    '#',
    '# Regenerate after changing node versions or after `npm run prebuild`,',
    '# which deletes ios/ wholesale.',
    `export NODE_BINARY=${nodeBinary}`,
    '',
  ].join('\n'),
);

console.log(`write-xcode-env: NODE_BINARY=${nodeBinary}`);
